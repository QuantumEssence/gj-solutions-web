-- 1. Create Inquiries Table
CREATE TABLE IF NOT EXISTS public.inquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  is_spmc TEXT NOT NULL,
  service_interest TEXT NOT NULL,
  schedule_meeting TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending Review',
  is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
  deleted_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Index frequently filtered columns for faster queries
CREATE INDEX IF NOT EXISTS idx_inquiries_is_deleted_created_at ON public.inquiries (is_deleted, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_inquiries_deleted_at ON public.inquiries (deleted_at DESC) WHERE is_deleted = TRUE;

-- 2. Create Page Views Table
CREATE TABLE IF NOT EXISTS public.page_views (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path TEXT NOT NULL,
  ip_hash TEXT NOT NULL,
  user_agent TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Index page views for analytics aggregation
CREATE INDEX IF NOT EXISTS idx_page_views_created_at ON public.page_views (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_page_views_ip_hash ON public.page_views (ip_hash);

-- 3. Row Level Security (RLS) Configuration
ALTER TABLE public.inquiries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.page_views ENABLE ROW LEVEL SECURITY;

-- 4. Policies for inquiries
-- Allow anonymous / public users to submit new inquiries (Contact questionnaire)
DROP POLICY IF EXISTS "Allow anonymous insert on inquiries" ON public.inquiries;
CREATE POLICY "Allow anonymous insert on inquiries"
ON public.inquiries
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- Allow backend service role full access (bypass RLS / manage inquiries)
DROP POLICY IF EXISTS "Service role full access on inquiries" ON public.inquiries;
CREATE POLICY "Service role full access on inquiries"
ON public.inquiries
FOR ALL
TO service_role
USING (true)
WITH CHECK (true);

-- 5. Policies for page_views
-- Allow anonymous / public tracking of page views
DROP POLICY IF EXISTS "Allow anonymous insert on page_views" ON public.page_views;
CREATE POLICY "Allow anonymous insert on page_views"
ON public.page_views
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- Allow backend service role full access to page_views
DROP POLICY IF EXISTS "Service role full access on page_views" ON public.page_views;
CREATE POLICY "Service role full access on page_views"
ON public.page_views
FOR ALL
TO service_role
USING (true)
WITH CHECK (true);

